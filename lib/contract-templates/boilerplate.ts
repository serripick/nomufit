export function getVacationClause(
  annualLeaveAllowancePrepaid: boolean,
  fiveOrMoreEmployees: boolean
): string[] {
  const base = [
    fiveOrMoreEmployees
      ? "1년간 80% 이상 출근한 경우 15일의 연차유급휴가를 부여한다. 다만 1년간 80% 미만 출근한 경우 및 계속근로연수가 1년 미만인 경우 전월 개근 시 익월에 1일의 연차유급휴가를 부여한다. 다만 4주 평균한 근로자의 1주 소정근로시간이 15시간 미만인 경우는 그러하지 아니하다."
      : "본 사업장은 상시근로자 5인 미만으로 근로기준법상 연차유급휴가 의무 적용 대상이 아니다. 다만 사업주는 근로자에게 1년간 80% 이상 출근한 경우 15일의 연차유급휴가를 부여한다.",
    "사업주가 근로기준법 제61조에 따라 연차유급휴가의 사용촉진을 하였음에도 불구하고 근로자가 휴가를 사용하지 않은 경우 미사용 연차유급휴가수당을 지급하지 않는다.",
    "근로자대표와의 합의로 특정 근로일을 연차휴가로 대체할 수 있다.",
    "휴직기간은 원칙적으로 근속기간에 산입하지 아니한다. 다만 예외적으로 육아휴직기간 등 법령에서 산입하도록 명시한 경우에는 근속기간에 산입한다.",
  ];
  if (annualLeaveAllowancePrepaid) {
    base.push(
      "사업주는 월급여에 미사용연차휴가수당을 포함하여 지급함을 이유로 근로자의 연차휴가 사용을 제한하지 아니한다. 다만 근로자가 연차휴가를 사용하는 경우 월급여에 포함하여 지급된 미사용연차휴가수당을 사후 정산하여 퇴사하는 월의 임금 등의 금품에서 공제함에 동의한다."
    );
  }
  base.push(
    "연차유급휴가는 계산의 편의상 회계연도 기준으로 부여할 수 있고, 퇴직 시 입사일 기준으로 재정산한다. 근로자는 연차휴가 초과사용일수에 대하여 퇴사하는 월의 임금 등의 금품에서 공제함에 동의한다."
  );
  return base;
}

